/**
 * Generate the command reference, in every supported language, from the catalog.
 *
 * The catalog is the single source of truth for what the editor accepts, and it
 * is itself generated from the C++ (`scripts/extract-methods.mjs`). A
 * hand-written command reference would be a third copy of the same facts, and
 * the one nobody re-checks. So this file is derived too, and `--check` fails when
 * it is stale — the same contract as `check-catalog.mjs`.
 *
 *   node scripts/gen-docs.mjs            # write docs/command-reference.md + docs/<lang>/command-reference.md
 *   node scripts/gen-docs.mjs --check    # exit 1 if any committed file is stale
 *
 * Run `npm run build` first: this reads the built `lib/`, so that what is
 * documented is exactly what ships.
 *
 * ## Why the command table stays in English
 *
 * Only the *structure* is translated — headings, table headers, risk-tier prose,
 * the generated-file notice. Command names, parameter keys, result keys, status
 * codes and the per-command summaries come straight from the catalog, which
 * comes straight from the C++ handlers. Those are literal identifiers: a
 * translated `actor.get_info` or `asset_path` would be actively harmful, since UE
 * silently ignores a key it does not recognize. The one-line summaries are prose,
 * but they are the catalog's own text and translating them here would mean 170
 * strings × 8 languages maintained outside the generator, which is exactly the
 * stale-copy problem this script exists to prevent.
 *
 * So: read the prose in your language, then copy the identifiers verbatim.
 */
