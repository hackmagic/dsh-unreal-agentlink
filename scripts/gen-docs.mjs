/**
 * The README link, relative to the directory the current file lives in. Every generated
 * copy lives inside `docs/` — the canonical one directly, each translation in its own
 * subdirectory — so the root README is always one hop up, and a translation's README is a
 * sibling of its language directory.
 */
const readmeLink = (lang) => (lang.dir === '' ? '../README.md' : `../readme/README_${lang.code}.md`)

/** Language switcher bar, relative to the directory the current file lives in. */
const switcher = (fromDir) =>
  LANGUAGES.map((l) => {
    const prefix = l.dir === fromDir ? '' : l.dir === '' ? '../' : `${fromDir === '' ? '' : '../'}${l.dir}/`
    const link = `${prefix}command-reference.md`
    return l.dir === fromDir ? `**${l.label}**` : `[${l.label}](${link})`
  }).join(' · ')

/** Markdown table cells cannot contain a bare `|` or a newline. */
const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim()
/** Wrap in backticks unless it is prose that already reads fine. */
const code = (keys) => (keys.length === 0 ? '—' : keys.map((k) => `\`${k}\``).join(' '))

const familyOf = (method) => method.slice(0, method.indexOf('.'))
const families = new Map()
for (const method of METHOD_NAMES) {
  const family = familyOf(method)
  if (!families.has(family)) families.set(family, [])
  families.get(family).push(method)
}
const sortedFamilies = [...families].sort((a, b) => a[0].localeCompare(b[0]))

const counts = Object.fromEntries(RISK_ORDER.map((risk) => [risk, 0]))
for (const method of METHOD_NAMES) counts[specOf(method).risk] += 1

const drift = CATALOG_DRIFT.length === 0 ? null : CATALOG_DRIFT.length

function render(lang) {
  const t = S[lang.code]
  const lines = []
  const push = (...text) => lines.push(...text)

  push(
    '<div align="center">',
    '',
    switcher(lang.dir),
    '',
    `[README](${readmeLink(lang)})`,
    '',
    '</div>',
    '',
    `# ${t.title}`,
    '',
    ...t.notice,
    '',
    t.methods(METHOD_NAMES.length, families.size),
    t.risk(counts),
    t.drift(drift === null ? t.driftZero : t.driftN(drift)),
    '',
    ...t.notes,
    '',
    `## ${t.riskHeading}`,
    '',
    ...t.riskTable,
    ...t.riskRows,
    '',
    t.riskNote(counts.destructive + counts.dangerous),
    '',
    `## ${t.familyHeading}`,
    '',
    ...t.familyTable,
  )

  for (const [family, methods] of sortedFamilies) {
    const tally = Object.fromEntries(RISK_ORDER.map((risk) => [risk, methods.filter((m) => specOf(m).risk === risk).length]))
    push(`| \`${family}\` | ${methods.length} | ${tally.read} | ${tally.write} | ${tally.destructive} | ${tally.dangerous} |`)
  }

  push('', `## ${t.commandsHeading}`, '')

  for (const [family, methods] of sortedFamilies) {
    push(`### \`${family}\` (${methods.length})`, '', ...t.commandTable)
    for (const method of [...methods].sort()) {
      const spec = specOf(method)
      const required = requiresOf(method)
      const timeout = spec.blocking ? t.blocking(Math.round((spec.timeoutMs ?? 0) / 1000)) : t.timeoutDefault
      const note = spec.warning ? `${cell(spec.summary)}<br>⚠️ ${cell(spec.warning)}` : cell(spec.summary)
      push(`| \`${method}\` | ${RISK_LABEL[spec.risk]} | ${code(paramKeysOf(method))} | ${code(required)} | ${timeout} | ${note} |`)
    }
    push('')
  }

  push(`## ${t.resultsHeading}`, '', t.resultsIntro, '', ...t.resultTable)
  for (const method of METHOD_NAMES) {
    const keys = RESULT_KEYS[method] ?? []
    const codes = codesOf(method)
    push(`| \`${method}\` | ${code(keys)} | ${codes.length === 0 ? '200' : codes.join(' / ')} |`)
  }
  push('')

  const blocked = Object.keys(BLACKLIST)
  push(`## ${t.blockedHeading}`, '', ...t.blockedIntro, '', ...t.blockedTable)
  for (const method of blocked.sort()) push(`| \`${method}\` | ${cell(BLACKLIST[method])} |`)
  push('')

  return lines.join('\n')
}

const outputs = LANGUAGES.map((lang) => ({
  lang,
  path: join(repo, 'docs', ...(lang.dir === '' ? [] : [lang.dir]), 'command-reference.md'),
  text: render(lang),
}))

if (check) {
  const stale = outputs.filter((o) => !existsSync(o.path) || readFileSync(o.path, 'utf8') !== o.text)
  if (stale.length > 0) {
    console.error(
      `command reference is STALE for: ${stale.map((o) => o.lang.code).join(', ')}\n` +
        '  run: npm run build && node scripts/gen-docs.mjs',
    )
    process.exit(1)
  }
  console.log(`command reference is current in ${outputs.length} languages (${METHOD_NAMES.length} methods, ${families.size} families)`)
} else {
  for (const o of outputs) {
    mkdirSync(dirname(o.path), { recursive: true })
    writeFileSync(o.path, o.text)
  }
  console.log(
    `wrote command reference in ${outputs.length} languages: ${METHOD_NAMES.length} methods, ${families.size} families`,
  )
}
